import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startNativeRuntime, workspaceRoot } from '../scripts/native-runtime.mjs';
import { openLibrary, openGraph } from '../scripts/ui-navigation.mjs';

test('native rightbar browser and file tools coexist with Notara library, graph and readers', { timeout: 90_000 }, async () => {
  const site = createServer((request, response) => {
    response.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
    response.end('<!doctype html><html><head><title>原生网页回归</title></head><body><h1>原生网页仍可阅读</h1><a href="/second">第二页</a></body></html>');
  });
  await new Promise(resolve => site.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${site.address().port}/`;
  const runtime = await startNativeRuntime({ testModel: true });
  await writeFile(join(runtime.vault, '原生回退.markdown'), 'NATIVE_VIEWER_FALLBACK');
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1414, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const output = join(workspaceRoot, 'outputs/rightbar-coexistence-20261026');
  const presentation = () => page.evaluate(() => document.documentElement.dataset.notaraConversationMode ?? 'split');
  try {
    await page.goto(runtime.authUrl);
    await page.getByRole('button', { name: /^(Continue|继续)$/ }).click();
    await page.locator('[data-composer-input]:visible').waitFor();
    await page.waitForLoadState('networkidle');
    await page.locator('[data-composer-input]').pressSequentially('右侧栏共存验收草稿，不发送');
    await page.locator('[data-sidebar-right-expand]').click();
    await expect(page.locator('[data-sidebar-right-guide-entry="browser"]')).toBeVisible({ timeout: 5000 });
    await expect(page.getByRole('button', { name: /^(工作区文件|Workspace files)/ })).toBeVisible();
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: join(output, 'start-page.png') });
    await page.locator('[data-sidebar-right-guide-entry="browser"]').click();
    await page.getByRole('textbox', { name: /^(输入 HTTP\(S\) 地址|Enter an HTTP\(S\) address)$/ }).fill(url);
    await page.getByRole('button', { name: /^(前往|Go)$/ }).click();
    await expect(page.frameLocator('[data-sidebar-browser-frame="iframe"]').getByRole('heading', { name: '原生网页仍可阅读' })).toBeVisible();
    const browserTab = await page.locator('[data-dockkit-tab][aria-selected="true"]').getAttribute('data-dockkit-tab');
    for (const name of [/^(后退|Back)$/, /^(前进|Forward)$/, /^(刷新|Reload)$/, /^(在系统浏览器中打开|Open in system browser)$/]) await expect(page.getByRole('button', { name })).toBeVisible();
    assert.equal(await presentation(), 'split');
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: join(output, 'native-browser.png') });
    await openLibrary(page);
    await page.locator('.nv-base-workspace:visible').waitFor();
    await openGraph(page);
    await page.locator('.nv-independent-graph:visible').waitFor();
    await page.locator('.nv-left-files-body').getByRole('button', { name: '奇异值分解SVD的几何意义与构造推导', exact: true }).click();
    await page.locator('.nv-vault-doc-tab:visible .cm-editor').waitFor();
    await page.locator('.nv-left-files-body').getByRole('button', { name: '集成测试讲义', exact: true }).click();
    await page.locator('.nv-vault-doc-tab:visible .nv-vault-pdf').waitFor();
    await page.getByRole('button', { name: /^(新标签页|New tab)$/ }).click();
    await page.getByRole('button', { name: /^(工作区文件|Workspace files)/ }).click();
    await page.locator('[data-files-state="tree"]').waitFor();
    const filesTab = await page.locator('[data-dockkit-tab][aria-selected="true"]').getAttribute('data-dockkit-tab');
    await page.locator('[data-files-entry="file"][data-files-path$="/00-学习画像与偏好.md"] button').click();
    await expect(page.locator('.nv-vault-doc-tab:visible .cm-editor')).toBeVisible({ timeout: 5000 });
    await page.locator(`[data-dockkit-tab="${filesTab}"]`).click();
    await page.locator('[data-files-entry="file"][data-files-path$="/原生回退.markdown"] button').click();
    await expect(page.getByText('NATIVE_VIEWER_FALLBACK', { exact: true })).toBeVisible();
    await expect(page.locator('.nv-vault-doc-tab:visible')).toHaveCount(0);
    await page.locator(`[data-dockkit-tab="${filesTab}"]`).click();
    await page.locator('[data-files-entry="directory"][data-files-path$="/来源"] > button').click();
    await page.locator('[data-files-entry="file"][data-files-path$="/集成测试讲义.pdf"] button').click();
    await expect(page.locator('.nv-vault-doc-tab:visible .nv-vault-pdf')).toBeVisible({ timeout: 5000 });
    assert.equal(await presentation(), 'split');
    await page.getByRole('button', { name: '全屏', exact: true }).click();
    await expect.poll(presentation).toBe('floating');
    await page.locator(`[data-dockkit-tab="${browserTab}"]`).click();
    await expect(page.frameLocator('[data-sidebar-browser-frame="iframe"]').getByRole('heading', { name: '原生网页仍可阅读' })).toBeVisible();
    assert.equal(await presentation(), 'floating', 'Native browser switch preserves the selected presentation');
    await page.getByRole('button', { name: /^(新标签页|New tab)$/ }).click();
    await expect(page.locator('[data-sidebar-right-guide-entry="browser"]')).toBeVisible();
    await expect(page.locator('[data-sidebar-right-guide-entry="notara-library"]')).toBeVisible();
    await expect(page.locator('[data-sidebar-right-guide-entry="notara-graph"]')).toBeVisible();
    assert.equal(await presentation(), 'floating');
    await page.locator('[data-sidebar-right-guide-entry="notara-library"]').click();
    await page.locator('.nv-base-workspace:visible').waitFor();
    assert.equal(await presentation(), 'floating');
    await page.getByRole('button', { name: '退出全屏', exact: true }).click();
    await expect.poll(presentation).toBe('split');
    await page.locator(`[data-dockkit-tab="${browserTab}"]`).click();
    await page.reload();
    await expect(page.getByRole('textbox', { name: /^(输入 HTTP\(S\) 地址|Enter an HTTP\(S\) address)$/ })).toHaveValue(url);
    await expect(page.locator('[data-composer-input]')).toHaveText('右侧栏共存验收草稿，不发送');
    await expect(page.locator('.nv-doc-tab-chip').filter({ hasText: /^资料库$/ })).toHaveCount(1);
    await expect(page.locator('.nv-doc-tab-chip').filter({ hasText: /^知识图谱$/ })).toHaveCount(1);
    await page.screenshot({ path: join(output, 'coexisting-tabs.png') });
    assert.deepEqual(errors, []);
  } finally {
    await browser.close(); await runtime.stop();
    await new Promise(resolve => site.close(resolve));
  }
});
