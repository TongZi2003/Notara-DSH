import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,rm,mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {chromium,expect} from '@playwright/test';
import {startNativeRuntime,workspaceRoot} from '../scripts/native-runtime.mjs';
import {openLibrary,chooseBaseView} from '../scripts/ui-navigation.mjs';

test('quiet library preserves discoverable search, filters, multi-selection and native chat entry', {timeout:90000}, async()=>{
  const fixture=await mkdtemp(join(workspaceRoot,'work/student-surfaces-'));
  await writeFile(join(fixture,'讲义.md'),'---\ntype: source\n---\n# 讲义\n原始材料。');
  await writeFile(join(fixture,'知识点.md'),'---\ntype: concept\ntags: [条件]\n---\n# 知识点\n\n## 来源\n[[讲义.md]]\n');
  const runtime=await startNativeRuntime({fixture,testModel:true}),browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1150,height:800}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(10000);
  const output=join(workspaceRoot,'outputs/ui-student-surface-regression');await mkdir(output,{recursive:true});
  try{
    await page.goto(runtime.authUrl);await page.getByRole('button',{name:/^(Continue|继续)$/}).click();
    const input=page.locator('[data-composer-input]:visible');await input.waitFor();
    await expect(input).toHaveAttribute('data-placeholder',/^(今天想弄懂什么？|What would you like to understand today\?)$/);
    await page.waitForLoadState('networkidle');
    await input.pressSequentially('保留这份草稿');
    await page.locator('.nv-left-ws-header').getByRole('button',{name:'新会话',exact:true}).click();
    await expect(input).toHaveText('保留这份草稿');
    const skills=page.locator('.nr-skill-entrances');await expect(skills.getByRole('button')).toHaveCount(4);
    await skills.getByRole('button',{name:'试卷诊断与补强',exact:true}).click();
    await expect(input).toContainText('保留这份草稿');await expect(input).toContainText('/notara-exam-diagnosis');
    await skills.getByRole('button',{name:'试卷诊断与补强',exact:true}).click();
    assert.equal((await input.innerText()).split('/notara-exam-diagnosis').length,2);
    const draft=await input.innerText();
    await openLibrary(page);await page.getByRole('button',{name:'全屏',exact:true}).click();
    const base=page.locator('.nv-base-workspace:visible');
    await expect(base.locator('.nv-base-result-count')).toHaveText('2 个结果');
    await expect(base.locator('.nv-base-footer')).toHaveCount(0);
    await expect(base.getByRole('searchbox',{name:'搜索资料'})).toHaveCount(0);
    await expect(base.getByRole('button',{name:'筛选来源',exact:true})).toHaveCount(0);
    await expect(base.getByRole('button',{name:'切换保存的视图'})).toHaveCSS('border-top-width','0px');
    const row=base.locator('.nv-base-data-row').first();
    assert.ok((await row.getByRole('gridcell').first().boundingBox()).height<=32);
    await expect(base.getByRole('checkbox',{name:/^选择 /})).toHaveCount(0);await expect(row.getByRole('gridcell')).toHaveCount(1);
    const titleBox=await row.locator('.nv-vault-title-link').boundingBox();
    const resultLeft=await base.locator('.nv-base-results').evaluate(el=>el.getBoundingClientRect().left+parseFloat(getComputedStyle(el).paddingLeft));
    assert.ok(titleBox.x-resultLeft>=8&&titleBox.x-resultLeft<=12,'title retains the normal content inset without a selection column');
    await base.getByRole('button',{name:'资料库操作',exact:true}).click();
    await page.getByRole('menuitem',{name:'多选资料',exact:true}).click();await row.locator('.nv-vault-title-link').click();
    await expect(row).toHaveAttribute('aria-selected','true');await expect(base.locator('.nv-library-source-heading')).toHaveCount(0);
    await expect(base.getByRole('button',{name:'批量带入当前对话',exact:true})).toBeEnabled();
    await base.getByRole('button',{name:'取消选择',exact:true}).click();
    await base.getByRole('button',{name:'结束多选',exact:true}).click();
    const titles=base.locator('.nv-base-data-row .nv-vault-title-link');
    await titles.nth(0).click({modifiers:['ControlOrMeta']});
    await titles.nth(1).click({modifiers:['Shift']});
    await expect(base.getByRole('row',{selected:true})).toHaveCount(2);
    await expect(base.locator('.nv-library-source-heading')).toHaveCount(0);
    await titles.nth(0).click({modifiers:['Meta']});
    await expect(base.getByRole('row',{selected:true})).toHaveCount(1);
    await titles.nth(0).press('Control+Space');
    await expect(base.getByRole('row',{selected:true})).toHaveCount(2);
    await base.getByRole('button',{name:'取消选择',exact:true}).click();
    await base.getByRole('button',{name:'搜索',exact:true}).click();
    await base.getByRole('searchbox',{name:'搜索资料',exact:true}).fill('不存在');
    await expect(base.locator('.nv-base-result-count')).toHaveText('0 个结果');
    await base.getByRole('searchbox',{name:'搜索资料',exact:true}).fill('');
    await expect(base.locator('.nv-base-result-count')).toHaveText('2 个结果');
    await base.getByRole('button',{name:'搜索',exact:true}).click();
    await base.getByRole('button',{name:'筛选',exact:true}).click();
    await page.getByRole('dialog',{name:'筛选',exact:true}).getByLabel('筛选资料类型').selectOption('concept');
    await page.getByRole('button',{name:'关闭筛选',exact:true}).click();
    await expect(base.getByRole('button',{name:'知识点',exact:true})).toBeVisible();
    await expect(base.getByRole('button',{name:'筛选',exact:true})).toHaveAttribute('data-active','true');
    await expect(base.getByRole('button',{name:'筛选标签 条件',exact:true})).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
    await chooseBaseView(page,'全部资料');await base.getByRole('button',{name:'卡片布局',exact:true}).click();
    const card=base.locator('.nv-vault-card').filter({has:page.getByRole('button',{name:'知识点',exact:true})});
    await expect(card.getByRole('checkbox',{name:/^选择 /})).toHaveCount(0);
    await card.getByRole('button',{name:'知识点',exact:true}).click({modifiers:['ControlOrMeta']});await expect(card).toHaveClass(/is-picked/);
    await card.press('Control+Space');await expect(card).not.toHaveClass(/is-picked/);
    await base.getByRole('button',{name:'资料库操作',exact:true}).click();await page.getByRole('menuitem',{name:'多选资料',exact:true}).click();
    await card.getByRole('button',{name:'知识点',exact:true}).click();await expect(card).toHaveClass(/is-picked/);
    await card.press('Space');await expect(card).not.toHaveClass(/is-picked/);await base.getByRole('button',{name:'结束多选',exact:true}).click();
    await chooseBaseView(page,'原始资料');
    await page.getByRole('button',{name:'最小化会话',exact:true}).click();
    const bubble=page.getByRole('button',{name:'展开悬浮会话',exact:true});await expect(bubble).toHaveText('');
    assert.ok((await bubble.boundingBox()).width<=36);
    await page.screenshot({path:join(output,'library.png')});
    await page.setViewportSize({width:642,height:746});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:join(output,'library-narrow.png')});
    await bubble.click();await expect(input).toHaveText(draft);
    await input.press('Enter');
    await page.locator('section.nv-block-flow').waitFor();
    await expect(skills).toHaveCount(0);
    assert.deepEqual(errors,[]);
  }catch(e){await page.screenshot({path:join(output,'failure.png')});throw e;}
  finally{await browser.close();await runtime.stop();await rm(fixture,{recursive:true,force:true});}
});
