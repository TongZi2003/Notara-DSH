import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startNativeRuntime, workspaceRoot } from '../scripts/native-runtime.mjs';
import { openLibrary, openGraph, chooseWorkspace, graphAction } from '../scripts/ui-navigation.mjs';

test('ordinary file links, library rows and graph nodes open the native viewer and preserve draft/layout', {timeout:90_000}, async () => {
  const fixture = await mkdtemp(join(workspaceRoot,'work/file-reference-fixture-'));
  await mkdir(join(fixture,'代码/阶段0'),{recursive:true});
  await writeFile(join(fixture,'代码/阶段0/lesson01_train_loop.py'),'# REFERENCE_PY_A\nprint("hello")\n');
  await writeFile(join(fixture,'结果.json'),'{"result":"REFERENCE_JSON_A"}\n');
  await writeFile(join(fixture,'说明 文档.txt'),'REFERENCE_TXT_A\n');
  await writeFile(join(fixture,'Makefile'),'REFERENCE_MAKE_A\n');
  await writeFile(join(fixture,'实验笔记.md'),'# 实验笔记\n\n代码：[[代码/阶段0/lesson01_train_loop.py|训练脚本]]\n\n[运行结果](结果.json)\n\n![[说明 文档.txt]]\n');
  const runtime = await startNativeRuntime({fixture,testModel:true,modelFixture:'tests/file-reference-model.mjs'});
  const browser=await chromium.launch({headless:true}), page=await browser.newPage({viewport:{width:1414,height:850}}), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const output=join(workspaceRoot,'outputs/file-references-20261026'); await mkdir(output,{recursive:true});
  const mode=()=>page.evaluate(()=>document.documentElement.dataset.notaraConversationMode||'split');
  try {
    await page.goto(runtime.authUrl); await page.getByRole('button',{name:/^(Continue|继续)$/}).click();
    await page.locator('[data-composer-input]:visible').waitFor();
    await page.getByRole('button',{name:'首页学习助手',exact:true}).click();
    await page.getByRole('menuitem',{name:/^专题课堂老师/}).click();
    const composer=page.locator('[data-composer-input]');
    await composer.pressSequentially('请列出这次实验的文件。');
    await expect(composer).toHaveText('请列出这次实验的文件。');
    await page.getByRole('button',{name:/^(Send message|发送消息)$/}).click();
    const response=page.locator('.nv-chat-markdown');
    await expect(response.getByRole('button',{name:'训练脚本',exact:true})).toBeVisible();
    assert.doesNotMatch(await response.innerText(),/\[\[/);
    await composer.pressSequentially('保留我的学习草稿');
    await response.getByRole('button',{name:'训练脚本',exact:true}).click();
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    await expect(page.locator('.nv-vault-doc-tab:visible')).toHaveCount(0);
    const initial=await mode();
    await response.getByRole('button',{name:'代码第二行',exact:true}).click();
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    await response.getByRole('button',{name:'运行结果',exact:true}).click();
    await expect(page.getByText('"REFERENCE_JSON_A"',{exact:true})).toBeVisible();
    await response.getByRole('button',{name:'说明文本',exact:true}).click();
    await expect(page.getByText('REFERENCE_TXT_A',{exact:true})).toBeVisible();
    await response.getByRole('button',{name:'实验笔记',exact:true}).click();
    const document=page.locator('.nv-vault-doc-tab:visible');
    await expect(document.locator('.cm-editor')).toBeVisible();
    await document.getByRole('button',{name:'训练脚本',exact:true}).click();
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    await openLibrary(page);
    await page.locator('.nv-base-workspace:visible').getByRole('button',{name:'lesson01_train_loop.py',exact:true}).click();
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    await openGraph(page);
    const graph=page.locator('.nv-independent-graph:visible');
    // The default source map excludes auxiliary files; their own centre view
    // remains the supported route to inspect and open them from the graph.
    await graphAction(page,graph,{name:'中心节点',exact:true});
    const centers=page.getByRole('dialog',{name:'中心节点',exact:true});
    await centers.getByRole('searchbox',{name:'查找中心资料',exact:true}).fill('lesson01_train_loop.py');
    await centers.getByRole('checkbox',{name:'中心资料 lesson01_train_loop.py',exact:true}).check();
    await centers.getByRole('button',{name:'应用',exact:true}).click();
    await expect(graph.getByRole('button',{name:'lesson01_train_loop.py，按回车打开',exact:true})).toBeVisible();
    await graph.getByRole('button',{name:'lesson01_train_loop.py，按回车打开',exact:true}).click();
    await expect(graph.getByRole('complementary',{name:'选中节点'})).toBeVisible();
    await page.screenshot({path:join(output,'code-file-graph.png')});
    await graph.getByRole('button',{name:'lesson01_train_loop.py，按回车打开',exact:true}).press('Enter');
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    assert.equal(await mode(),initial);
    await expect(composer).toHaveText('保留我的学习草稿');
    await page.screenshot({path:join(output,'code-link-native.png')});
    await page.reload();
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    await expect(composer).toHaveText('保留我的学习草稿');
    await expect(page.locator('[data-user-markdown]')).toHaveCount(1);
    const picker=page.getByRole('button',{name:'切换工作区',exact:true}), firstWorkspace=await picker.getAttribute('data-workspace-id');
    const second=join(runtime.root,'第二工作区');await mkdir(join(second,'代码/阶段0'),{recursive:true});
    await writeFile(join(second,'代码/阶段0/lesson01_train_loop.py'),'# REFERENCE_PY_B\nprint("different workspace")\n');
    await picker.click();await page.getByRole('menuitem',{name:'添加工作区…',exact:true}).click();
    await page.getByRole('button',{name:/^(编辑路径|Edit path)$/}).click();
    const path=page.getByRole('textbox',{name:/^(编辑路径|Edit path)$/});await path.fill(second);await path.press('Enter');
    await page.getByRole('button',{name:/^(打开|Open)$/}).click();
    await expect(picker).not.toHaveAttribute('data-workspace-id',firstWorkspace);
    await openLibrary(page);await page.locator('.nv-base-workspace:visible').getByRole('button',{name:'lesson01_train_loop.py',exact:true}).click();
    await expect(page.getByText('# REFERENCE_PY_B',{exact:true})).toBeVisible();
    await chooseWorkspace(page,firstWorkspace);
    await expect(page.getByText('# REFERENCE_PY_A',{exact:true})).toBeVisible();
    await expect(composer).toHaveText('保留我的学习草稿');
    await page.setViewportSize({width:755,height:746});
    await page.screenshot({path:join(output,'code-link-narrow.png')});
    assert.deepEqual(errors,[]);
  } catch(error) { await page.screenshot({path:join(output,'failure.png')}); throw error; }
  finally { await browser.close(); await runtime.stop(); await rm(fixture,{recursive:true,force:true}); }
});
