import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startNativeRuntime } from '../scripts/native-runtime.mjs';
import { chooseWorkspace } from '../scripts/ui-navigation.mjs';

test('top picker alone scopes sessions, search, native actions and folder selection', { timeout: 90_000 }, async () => {
  const runtime = await startNativeRuntime({ testModel: true, sessionSearch: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1150, height: 746 } });
  page.setDefaultTimeout(10_000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const list = page.getByRole('list', { name: '当前工作区会话' });
  const picker = page.getByLabel('切换工作区');
  const chooseSessions = () => page.getByRole('tablist', { name: '工作区栏目' }).getByRole('tab', { name: '会话', exact: true }).click();
  const rowAction = async (title, action) => {
    await list.getByRole('button', { name: `${title}的操作`, exact: true }).click();
    await page.getByRole('menuitem', { name: action, exact: true }).click();
  };
  const createNamedSession = async title => {
    const input = page.locator('[data-composer-input]');
    await input.fill(`${title} CONTENT_SCOPE_${title}`); await input.press('Enter');
    await page.locator('section.nv-block-flow').waitFor();
    await expect(page.locator('.nv-session-row')).toHaveCount(1);
    await list.locator('.nv-session-more').click();
    await page.getByRole('menuitem', { name: '重命名', exact: true }).click();
    const name = page.getByRole('textbox', { name: /Session name|会话名称/ });
    await name.fill(title); await name.press('Enter');
    // The button's accessible name also includes its live running status.
    await expect(list.locator('.nv-session-title')).toHaveText(title);
    // Fork operates on the last completed native turn, not merely streamed text.
    await expect(page.getByRole('button', { name: /^(Stop generating|停止生成)$/ })).toHaveCount(0, { timeout: 20_000 });
  };
  try {
    await page.goto(runtime.authUrl); await page.getByRole('button', { name: /^(Continue|继续)$/ }).click();
    await page.locator('[data-composer-input]:visible').waitFor(); await page.waitForLoadState('networkidle');
    await chooseSessions();
    await createNamedSession('甲课');
    const firstWorkspace = await picker.getAttribute('data-workspace-id');
    await rowAction('甲课', '置顶会话');
    await expect(list.locator('[data-pinned="true"]')).toHaveCount(1);
    const second = join(runtime.root, '第二工作区-很长的专题名称用于验证菜单和顶部文字不会挤压按钮');
    await mkdir(second); await writeFile(join(second, '乙资料.md'), '# 乙资料\n');
    await picker.click();
    await page.getByRole('menuitem', { name: '添加工作区…', exact: true }).click();
    await page.getByRole('button', { name: /^(编辑路径|Edit path)$/ }).click();
    const path = page.getByRole('textbox', { name: /^(编辑路径|Edit path)$/ });
    await path.fill(second); await path.press('Enter');
    await page.getByRole('button', { name: /^(打开|Open)$/ }).click();
    await expect(picker).not.toHaveAttribute('data-workspace-id', firstWorkspace);
    await page.locator('[data-composer-input]:visible').waitFor();
    await expect(list).not.toContainText('甲课');
    await createNamedSession('乙课');
    const secondWorkspace = await picker.getAttribute('data-workspace-id');
    await picker.click();
    const longOption = page.locator(`[data-workspace-option="${secondWorkspace}"]`);
    const geometry = await longOption.evaluate(element => {
      const prefix=element.querySelector('.nv-workspace-name>span:first-child'), tail=element.querySelector('.nv-workspace-name>span:last-child');
      return {prefixOverflows:prefix.scrollWidth>prefix.clientWidth,tail:tail.textContent,menu:element.closest('[role="menu"]').getBoundingClientRect().toJSON()};
    });
    assert.equal(geometry.prefixOverflows,true);assert.equal(geometry.tail,second.split('/').at(-1).slice(-8));
    assert.ok(geometry.menu.right <= page.viewportSize().width);
    const workspaceSearch=page.getByRole('textbox',{name:'搜索学习集',exact:true});
    await workspaceSearch.fill('没有这个学习集');await expect(page.getByText('没有匹配的学习集',{exact:true})).toBeVisible();
    await workspaceSearch.fill('第二工作区');await expect(page.locator('[data-workspace-option]')).toHaveCount(1);
    await workspaceSearch.press('Home');await expect(workspaceSearch).toBeFocused();
    await page.keyboard.press('Escape');
    await rowAction('乙课', '置顶会话');
    await expect(list.locator('[data-pinned="true"]')).toHaveCount(1);
    await chooseWorkspace(page, firstWorkspace);
    await expect(list).toContainText('甲课'); await expect(list).not.toContainText('乙课');
    await expect(page.locator('.hHd-Xa_regionArea')).toBeHidden();
    await expect(page.locator('.nv-left-ws-header').getByRole('button',{name:'新会话',exact:true})).toBeVisible();
    await picker.click();await expect(page.getByText('最近使用',{exact:true})).toBeVisible();await page.keyboard.press('Escape');
    const search = page.getByRole('searchbox', { name: '搜索会话' });
    await search.fill('CONTENT_SCOPE_乙课');
    await expect(page.getByText('当前工作区没有匹配的会话', { exact: true })).toBeVisible();
    await expect(list.getByRole('button')).toHaveCount(0);
    await search.fill('CONTENT_SCOPE_甲课');
    await expect(list.locator('.nv-session-title')).toHaveText('甲课');
    await search.fill('');
    await rowAction('甲课', '取消置顶');
    await expect(list.locator('[data-pinned="true"]')).toHaveCount(0);
    await chooseWorkspace(page, secondWorkspace);
    await expect(list).toContainText('乙课'); await expect(list).not.toContainText('甲课');
    await page.reload(); await chooseSessions();
    await expect(picker).toHaveAttribute('data-workspace-id', secondWorkspace);
    await expect(list).toContainText('乙课'); await expect(list).not.toContainText('甲课');
    await page.getByRole('tablist', { name: '工作区栏目' }).getByRole('tab', { name: '资料', exact: true }).click();
    await page.keyboard.press('Meta+Alt+k');
    await expect(search).toBeFocused();
    await expect(page.locator('.pI_x6G_frame')).not.toHaveAttribute('data-sidebar-collapsed', 'true');
    await page.getByRole('button', { name: /^(Collapse sidebar|收起侧边栏)$/ }).click();
    await expect(page.locator('.hHd-Xa_root')).toHaveClass(/hHd-Xa_collapsed/);
    await page.keyboard.press('Meta+Alt+k');
    await expect(search).toBeFocused();
    await expect(page.locator('.pI_x6G_frame')).not.toHaveAttribute('data-sidebar-collapsed', 'true');
    await page.getByRole('button', { name: /^(Collapse sidebar|收起侧边栏)$/ }).click();
    await page.keyboard.press('Meta+Alt+k');
    await expect(search).toBeFocused();
    await rowAction('乙课', '从这里分支');
    await expect(list.locator('.nv-session-row')).toHaveCount(2);
    await rowAction('乙课', '归档会话');
    await expect(picker).toHaveAttribute('data-workspace-id', secondWorkspace);
    await page.getByRole('button', { name: /^(filter archived sessions|筛选已归档会话)$/ }).click();
    await page.getByRole('button', { name: '筛选会话', exact: true }).click();
    await expect(page.getByRole('dialog').getByRole('radio', { name: '包含已归档', exact: true })).toBeChecked();
    await page.getByRole('dialog').getByRole('radio', { name: '只看已归档', exact: true }).check();
    await page.getByRole('dialog').getByRole('button', { name: '应用', exact: true }).click();
    await expect(list.locator('.nv-session-title')).toHaveText('乙课');
    await rowAction('乙课', '恢复会话');
    await expect(list.locator('.nv-session-row')).toHaveCount(0);
    await page.getByRole('button', { name: '筛选会话', exact: true }).click();
    await page.getByRole('dialog').getByRole('radio', { name: '当前会话', exact: true }).check();
    await page.getByRole('dialog').getByRole('button', { name: '应用', exact: true }).click();
    await list.locator('.nv-session-open[title="乙课"]').click();
    await expect(list.locator('.nv-session-row')).toHaveCount(2);
    assert.deepEqual(errors, []);
  } catch (error) {
    console.error(JSON.stringify({ errors, body: (await page.locator('body').innerText()).slice(-2500) }));
    throw error;
  } finally { await browser.close(); await runtime.stop(); }
});
