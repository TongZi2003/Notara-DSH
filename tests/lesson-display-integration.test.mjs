import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,mkdir,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {chromium,expect} from '@playwright/test';
import {startNativeRuntime,workspaceRoot} from '../scripts/native-runtime.mjs';
import {blurDocumentEditor,openDocumentSource} from '../scripts/ui-navigation.mjs';

test('bound lesson renders math and hidden metadata, preserves folds and exact source across editing and reload', {timeout:120000}, async () => {
  const fixture=await mkdtemp(join(workspaceRoot,'work/lesson-display-'));
  const original=(await readFile(new URL('./fixtures/lesson-display.md',import.meta.url),'utf8')).replace(/\n/g,'\r\n');
  await writeFile(join(fixture,'课稿显示回归.md'),original);
  await writeFile(join(fixture,'定义.md'),'# 定义\n\n同一单调区间上的比较依据。\n');
  const runtime=await startNativeRuntime({fixture,testModel:true});
  const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.setDefaultTimeout(10000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const output=join(workspaceRoot,'outputs/lesson-display-regression');await mkdir(output,{recursive:true});
  const read=()=>readFile(join(runtime.vault,'课稿显示回归.md'),'utf8');
  const doc=page.locator('.nv-vault-doc-tab:visible');
  try {
    await page.goto(runtime.authUrl);await page.getByRole('button',{name:/^(Continue|继续)$/}).click();
    await expect(page.getByRole('button',{name:/^(Continue|继续)$/})).toBeHidden();
    await page.waitForLoadState('networkidle');
    await page.locator('[data-composer-input]:visible').waitFor();
    await page.getByRole('button',{name:'首页学习助手',exact:true}).click();
    await page.getByRole('menuitem',{name:/^专题课堂老师/}).click();
    await page.locator('[data-composer-input]').fill('查看已有课稿');await page.getByRole('button',{name:/^(发送消息|Send message)$/}).click();
    await expect(page.getByText('这是确定性集成测试输出，不是教学效果证据。',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'本次活动',exact:true}).click();
    const panel=page.getByRole('complementary',{name:'本次活动',exact:true});
    await panel.getByRole('button',{name:/关联备课本/}).click();
    await page.getByRole('dialog',{name:'选择本课备课本'}).getByRole('button',{name:/课稿显示回归.md/}).click();
    const lesson=panel.getByRole('region',{name:'本课清单'});
    await expect(lesson.locator('.nv-lesson-focus .katex')).toHaveCount(2);
    await lesson.getByRole('button',{name:/进行中 1/}).click();
    await expect(lesson.locator('.nv-lesson-content .katex')).toHaveCount(3);
    await lesson.getByRole('button',{name:/打开课稿/}).click();
    await panel.getByRole('button',{name:'收起活动浮窗'}).click();
    await page.getByRole('button',{name:'全屏',exact:true}).click();
    await blurDocumentEditor(page,doc);
    const currentTask=doc.locator('.nv-route-bar-sub');
    await expect(currentTask.locator('strong')).toHaveText('等高点');
    await expect(currentTask.locator('.katex')).toHaveCount(2);
    await expect(currentTask.getByRole('button',{name:'定义',exact:true})).toBeVisible();
    await expect(currentTask.locator('code')).toHaveText('x > 0');
    assert.doesNotMatch(await currentTask.innerText(), /\*\*|\[\[|notara-task/);
    const summary=doc.locator('summary').filter({hasText:'教师总览'});
    await expect(summary.locator('strong')).toHaveText('条件');
    await expect(summary.locator('.katex')).toHaveCount(1);
    await expect(summary.locator('code')).toHaveText('先看范围');
    assert.doesNotMatch(await summary.innerText(), /\*\*|\[\[/);
    await expect(doc.getByText('教师总览应保持折叠。',{exact:true})).not.toBeVisible();
    await expect(doc.getByText('教师证明应保持折叠。',{exact:true})).not.toBeVisible();
    await expect(doc.locator('.nv-live-inline-math .katex-display')).toHaveCount(2);
    await expect(doc.locator('.nv-live-text').filter({hasText:'notara-task:task-'})).toHaveCount(0);
    await expect(doc.locator('pre').filter({hasText:'<!-- notara-task:literal -->'})).toHaveCount(1);
    assert.equal(await read(),original);
    const formula=doc.locator('.nv-live-inline-math').filter({has:page.locator('.katex-display')}).first();
    await formula.click();
    const dialog=page.getByRole('dialog',{name:'编辑公式'});
    await expect(dialog).toBeVisible();
    const tex=String.raw`P(x)=\begin{cases}(x-1)^2,&0<x\le1,\\ \dfrac{(x-1)^2}{4},&x>1.\end{cases}`;
    await expect(dialog.getByRole('textbox')).toHaveValue(tex);
    await dialog.getByRole('textbox').fill(tex+'\n+0');
    await dialog.getByRole('button',{name:'完成公式编辑'}).click();
    await doc.getByRole('button',{name:'保存',exact:true}).click();
    await expect.poll(read).toBe(original.replace(tex,tex+'\r\n  +0'));
    await doc.getByRole('button',{name:'撤销',exact:true}).click();
    await doc.getByRole('button',{name:'保存',exact:true}).click();
    await expect.poll(read).toBe(original);
    await blurDocumentEditor(page,doc);
    await summary.click({position:{x:8,y:8}});
    await expect(doc.getByText('教师总览应保持折叠。',{exact:true})).toBeVisible();
    await expect(doc.getByText('内层教师解答。',{exact:true})).not.toBeVisible();
    await doc.locator('summary').filter({hasText:'嵌套参考'}).click();
    await expect(doc.getByText('内层教师解答。',{exact:true})).toBeVisible();
    await summary.click({position:{x:8,y:8}});
    await openDocumentSource(page,doc);
    await expect(doc.getByRole('textbox',{name:'Markdown 正文编辑器'})).toContainText('<!-- notara-task:task-one -->');
    await doc.getByRole('button',{name:'返回正文',exact:true}).click();await blurDocumentEditor(page,doc);
    await page.reload();await expect(doc.getByRole('textbox',{name:'Markdown 实时预览编辑器'})).toBeVisible();
    await blurDocumentEditor(page,doc);
    await expect(doc.getByText('教师总览应保持折叠。',{exact:true})).not.toBeVisible();
    await expect(doc.locator('.nv-live-inline-math .katex-display')).toHaveCount(2);
    await expect(doc.locator('.katex-error')).toHaveCount(0);
    await expect(currentTask.locator('.katex')).toHaveCount(2);
    await expect(summary.locator('.katex')).toHaveCount(1);
    await summary.getByRole('button',{name:'定义',exact:true}).click();
    await expect(doc.getByRole('textbox',{name:'Markdown 实时预览编辑器'})).toContainText('同一单调区间上的比较依据');
    await page.locator('.nv-doc-tab-chip').filter({hasText:/^课稿显示回归$/}).click();
    await expect(doc.getByText('教师总览应保持折叠。',{exact:true})).not.toBeVisible();
    await currentTask.getByRole('button',{name:'定义',exact:true}).click();
    await expect(doc.getByRole('textbox',{name:'Markdown 实时预览编辑器'})).toContainText('同一单调区间上的比较依据');
    await page.locator('.nv-doc-tab-chip').filter({hasText:/^课稿显示回归$/}).click();
    await summary.press('Enter');
    await expect(doc.getByText('教师总览应保持折叠。',{exact:true})).toBeVisible();
    await summary.press('Space');
    await expect(doc.getByText('教师总览应保持折叠。',{exact:true})).not.toBeVisible();
    assert.equal(await read(),original);
    assert.deepEqual(errors,[]);
    await page.screenshot({path:join(output,'passed.png')});
  } catch(error) {await page.screenshot({path:join(output,'failure.png')});throw error;}
  finally {await browser.close();await runtime.stop();await rm(fixture,{recursive:true,force:true});}
});
