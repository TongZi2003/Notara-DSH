test('workspace RPCs bind registered roots, isolate identical revisions, and dispose cached stores', async t => {
  const root = mkdtempSync(join(tmpdir(), 'notara-workspaces-')), ctx = new Context();
  t.after(async () => { await ctx.fiber.dispose(); rmSync(root, { recursive: true, force: true }); });
  const a = join(root, 'a'), b = join(root, 'b'); mkdirSync(a); mkdirSync(b);
  const source = '---\ntype: card\n---\n# 同名\n- [ ] 学习\n';
  for (const dir of [a, b]) writeFileSync(join(dir, '同名.md'), source);
  ctx.provide('workspaceRegistry', { get: id => ({ a: { path: a }, b: { path: b } })[id] });
  await ctx.plugin(plugin, { root: a, cachePath: join(root, 'cache.sqlite') });
  const service = ctx.notaraVault, A = bindVaultRemote(service, 'a'), B = bindVaultRemote(service, 'b');
  const [first, second] = await Promise.all([A.read({ path: '同名.md' }), B.read({ path: '同名.md' })]);
  assert.equal(first.revision, second.revision);
  await B.toggleTask({ path: '同名.md', line: 5, checked: true, expectedRevision: second.revision });
  assert.match((await A.read({ path: '同名.md' })).content, /- \[ \]/);
  assert.match((await B.read({ path: '同名.md' })).content, /- \[x\]/);
  await B.recordReview({ path: '同名.md', result: 'done', support: 'hint', keyStep: 'fixture', note: 'fixture' });
  assert.equal((await A.query({})).documents[0].reviewCount, 0);
  assert.equal((await B.query({})).documents[0].reviewCount, 1);
  await B.undoReview({ path: '同名.md' });
  await B.save({ path: '仅B.md', content: '---\ntags: [仅B标签]\n---\n# B\n', expectedRevision: null });
  assert.equal((await A.query({facet:'tags'})).total,0);
  assert.deepEqual((await B.query({facet:'tags'})).values.map(item=>item.value),['仅B标签']);
  assert.equal((await A.graph({})).nodes.length, 1);
  assert.equal((await B.graph({})).nodes.length, 2);
  assert.equal((await B.homeRecommendations({})).due.total, 0);
  assert.equal((await service.query({})).total, 1);
  await assert.rejects(() => service.read({ workspaceId: 'missing', path: '同名.md' }), /workspace_not_found/);
  await assert.rejects(() => service.save({ workspaceId: '', path: '同名.md', content: 'bad' }), /workspace_invalid/);
  assert.equal(service.stores.size, 2);
  await ctx.fiber.dispose();
  await assert.rejects(() => B.query({}), /vault_closed/);
});

test('real Cordis, Typert discovery, Gateway invocation and unload/reload', async t => {
  const root = mkdtempSync(join(tmpdir(), 'notara-sdk-')), ctx = new Context();
  t.after(async () => { await ctx.fiber.dispose(); rmSync(root, { recursive: true, force: true }); });
  writeFileSync(join(root, 'A.md'), '# A\n');
  await ctx.plugin(TypertRegistry);
  await ctx.plugin(RemoteAccessService);
  await ctx.plugin(TypertGatewayService, {});
  const peer = new Peer(ctx, {principal:{kind:'owner'}});
  t.after(()=>peer.dispose());
  const fiber = ctx.plugin(plugin, { root, cachePath: join(root, 'vault-index.sqlite') }); await fiber;
  const service = ctx.get('notaraVault');
  assert.ok(service);
  assert.deepEqual(remoteMethods(service).map(row => row.method), VAULT_REMOTE_METHODS);
  assert.equal(REMOTE_CONTRIBUTION.descriptors.length, VAULT_REMOTE_METHODS.length);
  const invoke = (method, input = {}) => ctx.typertGateway.invoke({ namespace: 'notaraVault', method, args: { input }, peer });
  const result = await invoke('query');
  assert.equal(result.total, 1);
  const facet=await invoke('query',{facet:'tags',limit:40});assert.equal(facet.facet,'tags');assert.equal(facet.total,0);
  await invoke('save', { path: 'B.md', content: '---\ntype: card\n---\n# B\n- [ ] 学习\n', expectedRevision: null });
  await invoke('toggleTask', { path: 'B.md', line: 5, checked: true });
  await invoke('recordReview', { path: 'B.md', result: 'done', support: 'hint', keyStep: '判据', note: '看提示完成',followUp:{question:'再说判据',afterDays:2,reason:'关键步刚走通'} });
  assert.equal((await invoke('query', { reviewStatus: 'scheduled' })).total, 1);
  await invoke('undoReview', { path: 'B.md' });
  assert.equal((await invoke('query', { reviewStatus: 'new' })).total, 1);
  assert.equal((await invoke('read', { path: 'B.md' })).mimeType, 'text/markdown');
  assert.equal((await invoke('graph')).nodes.length, 2);
  assert.equal((await invoke('homeRecommendations')).due.total, 0);
  assert.equal((await service.read({ path: 'A.md' })).content, '# A\n');
  const controller = new AbortController();
  const updates = await ctx.typertGateway.stream({ namespace: 'notaraVault', method: 'changes', args: { input: {} }, peer, signal: controller.signal });
  const iterator = updates[Symbol.asyncIterator]();
  assert.deepEqual((await iterator.next()).value, { reset: true, changes: [] });
  const changed = await invoke('save', { path: 'A.md', content: '# A 已修改\n', expectedRevision: (await invoke('read', { path: 'A.md' })).revision });
  assert.deepEqual((await iterator.next()).value.changes, [{ path: 'A.md', revision: changed.revision }]);
  controller.abort(); await iterator.return();
  await fiber.dispose();
  assert.equal(ctx.get('notaraVault'), undefined);
  await assert.rejects(() => service.query({}), /vault_closed/);
  await assert.rejects(() => service.read({ path: 'A.md' }), /vault_closed/);
  const second = ctx.plugin(plugin, { root, cachePath: join(root, 'vault-index.sqlite') }); await second;
  assert.equal((await ctx.notaraVault.query({})).total, 2);
});
